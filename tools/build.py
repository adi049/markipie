JS = r'''/*! Markipie intro — premium animated wordmark reveal (vanilla JS, no dependencies).
 *  Usage:  MarkipieIntro.play({ siteSelector: '#site' })   → returns a Promise
 *  Also:   MarkipieIntro.renderWordmark(element, { width: 160 })  → static logo (header, footer…)
 *  Generated by tools/build.py — edit the source, not this file.
 */
(function (root, factory) {
  if (typeof module === 'object' && module.exports) { module.exports = factory(root); }
  else { root.MarkipieIntro = factory(root); }
}(typeof window !== 'undefined' ? window : this, function (root) {
  'use strict';

  var SVG_NS = 'http://www.w3.org/2000/svg';
  var VIEWBOX = __VIEWBOX__;
  var COLORS = __COLORS__;
  /* Every glyph of the wordmark as an independent vector shape (logo units, y down). */
  var LETTERS = __LETTERS__;

  /* Timeline (ms) */
  var T = {
    start: 300,        // empty screen before the first letter
    stagger: 110,      // gap between letters
    letter: 900,       // duration of one letter's entry
    tris: 640,         // pie-piece triangles, relative to the M's start
    triStagger: 55,
    check: 1560,       // check mark pop (after the last letter has landed)
    glow: 1650,
    shine: 1780,
    exit: 2900,        // wordmark complete & steady for ~1 s, then transition
    exitDuration: 800,
    reduced: { fade: 600, exit: 1600, exitDuration: 520 }
  };

  var uidCounter = 0;
  var reduceMotion = false;
  try {
    reduceMotion = !!(root.matchMedia && root.matchMedia('(prefers-reduced-motion: reduce)').matches);
  } catch (e) { /* ignore */ }

  function el(tag, attrs, parent) {
    var node = document.createElementNS(SVG_NS, tag);
    if (attrs) { for (var k in attrs) { if (attrs[k] != null) { node.setAttribute(k, attrs[k]); } } }
    if (parent) { parent.appendChild(node); }
    return node;
  }

  function fillFor(letter, uid, mono) {
    if (mono) { return mono; }
    if (letter.fill === 'gradM') { return 'url(#' + uid + '-gradM)'; }
    return COLORS[letter.fill] || COLORS.cyan;
  }

  function addGradient(svg, uid, letter) {
    var defs = el('defs', null, svg);
    var g = el('linearGradient', {
      id: uid + '-gradM', gradientUnits: 'userSpaceOnUse',
      x1: letter.grad[0], y1: 0, x2: letter.grad[1], y2: 0
    }, defs);
    el('stop', { offset: '0', 'stop-color': COLORS.blue }, g);
    el('stop', { offset: '1', 'stop-color': COLORS.teal }, g);
  }

  /* Draw one letter into an <svg> (or any container element in the same coordinate space). */
  function drawLetter(container, letter, uid, opts) {
    opts = opts || {};
    var fill = fillFor(letter, uid, opts.mono);
    var pathAttrs = { d: letter.d, fill: fill };
    if (opts.className) { pathAttrs['class'] = opts.className; }
    el('path', pathAttrs, container);
    if (letter.tris) {
      for (var i = 0; i < letter.tris.length; i++) {
        var a = { d: letter.tris[i], fill: fill };
        if (opts.triClass) { a['class'] = opts.triClass; }
        var tri = el('path', a, container);
        if (opts.triDelay != null) {
          /* bottom piece first, top piece last */
          var order = letter.tris.length - 1 - i;
          tri.style.setProperty('--d', (opts.triDelay + order * T.triStagger) + 'ms');
        }
      }
    }
  }

  function makeLetterSvg(letter, uid, opts) {
    var b = letter.box;
    var svg = el('svg', {
      viewBox: b[0] + ' ' + b[1] + ' ' + b[2] + ' ' + b[3],
      preserveAspectRatio: 'none', 'aria-hidden': 'true', focusable: 'false'
    });
    svg.style.left = ((b[0] - VIEWBOX[0]) / VIEWBOX[2] * 100) + '%';
    svg.style.top = ((b[1] - VIEWBOX[1]) / VIEWBOX[3] * 100) + '%';
    svg.style.width = (b[2] / VIEWBOX[2] * 100) + '%';
    svg.style.height = (b[3] / VIEWBOX[3] * 100) + '%';
    if (letter.grad) { addGradient(svg, uid, letter); }
    drawLetter(svg, letter, uid, opts);
    return svg;
  }

  /* Full wordmark in one <svg> — used for the glow layer, the shimmer clip and static usage. */
  function makeWordmarkSvg(uid, opts) {
    opts = opts || {};
    var svg = el('svg', {
      viewBox: VIEWBOX.join(' '), 'aria-hidden': opts.label ? null : 'true',
      role: opts.label ? 'img' : null, focusable: 'false'
    });
    if (opts.label) {
      var title = el('title', null, svg);
      title.textContent = opts.label;
    }
    var host = svg;
    for (var i = 0; i < LETTERS.length; i++) {
      if (LETTERS[i].grad) { addGradient(svg, uid, LETTERS[i]); }
    }
    if (opts.clipId) {
      var defs = el('defs', null, svg);
      host = el('clipPath', { id: opts.clipId }, defs);
    }
    for (var j = 0; j < LETTERS.length; j++) {
      drawLetter(host, LETTERS[j], uid, { mono: opts.mono });
    }
    return svg;
  }

  /* Public: render the static wordmark anywhere on the site (keeps the brand pixel-identical). */
  function renderWordmark(target, opts) {
    opts = opts || {};
    var uid = 'mk' + (++uidCounter);
    var svg = makeWordmarkSvg(uid, { label: opts.label || 'Markipie' });
    if (opts.width) {
      svg.setAttribute('width', opts.width);
      svg.setAttribute('height', Math.round(opts.width * VIEWBOX[3] / VIEWBOX[2] * 100) / 100);
    }
    if (opts.className) { svg.setAttribute('class', opts.className); }
    if (target) { target.appendChild(svg); }
    return svg;
  }

  /* Build the overlay DOM */
  function buildIntro(rootEl) {
    var uid = 'mk' + (++uidCounter);
    rootEl.className = 'mk-intro' + (reduceMotion ? ' mk-intro--reduced' : '');
    rootEl.setAttribute('aria-hidden', 'true');
    rootEl.innerHTML = '';

    var bg = document.createElement('div');
    bg.className = 'mk-intro__bg';
    rootEl.appendChild(bg);

    var wm = document.createElement('div');
    wm.className = 'mk-wordmark';
    wm.setAttribute('role', 'img');
    wm.setAttribute('aria-label', 'Markipie');
    rootEl.appendChild(wm);

    /* glow layer (blurred copy, opacity animated only) */
    var glow = makeWordmarkSvg(uid + 'g');
    glow.setAttribute('class', 'mk-glow');
    wm.appendChild(glow);

    /* letters */
    var letters = LETTERS.slice().sort(function (a, b) { return (a.order || 0) - (b.order || 0); });
    for (var i = 0; i < letters.length; i++) {
      var L = letters[i];
      var isCheck = L.id === 'check';
      var delay = isCheck ? T.check : T.start + L.order * T.stagger;
      if (reduceMotion) { delay = 0; }
      var svg = makeLetterSvg(L, uid + L.id, {
        triClass: 'mk-tri',
        triDelay: reduceMotion ? 0 : delay + T.tris
      });
      svg.setAttribute('class', isCheck ? 'mk-check' : 'mk-letter');
      svg.setAttribute('data-letter', L.char);
      if (L.dir) {
        svg.style.setProperty('--ux', L.dir[0]);
        svg.style.setProperty('--uy', L.dir[1]);
      }
      svg.style.setProperty('--d', delay + 'ms');
      wm.appendChild(svg);
    }

    /* shimmer layer */
    var clipId = uid + '-clip';
    var shine = makeWordmarkSvg(uid + 's', { clipId: clipId, mono: '#fff' });
    shine.setAttribute('class', 'mk-shine');
    var defs = shine.querySelector('defs');
    var grad = el('linearGradient', { id: uid + '-shine', x1: '0', y1: '0', x2: '1', y2: '0' }, defs);
    el('stop', { offset: '0',    'stop-color': '#fff', 'stop-opacity': '0' }, grad);
    el('stop', { offset: '0.42', 'stop-color': '#fff', 'stop-opacity': '0.55' }, grad);
    el('stop', { offset: '0.5',  'stop-color': '#fff', 'stop-opacity': '0.85' }, grad);
    el('stop', { offset: '0.58', 'stop-color': '#fff', 'stop-opacity': '0.55' }, grad);
    el('stop', { offset: '1',    'stop-color': '#fff', 'stop-opacity': '0' }, grad);
    var clipped = el('g', { 'clip-path': 'url(#' + clipId + ')' }, shine);
    var skew = el('g', { transform: 'skewX(-18)' }, clipped);
    el('rect', {
      'class': 'mk-shine__band', x: -70, y: VIEWBOX[1] - 20, width: 78, height: VIEWBOX[3] + 40,
      fill: 'url(#' + uid + '-shine)'
    }, skew);
    wm.appendChild(shine);

    return rootEl;
  }

  var state = { playing: false, finished: false, timers: [], root: null, site: null, resolve: null };

  function later(fn, ms) { state.timers.push(setTimeout(fn, ms)); }
  function clearTimers() { while (state.timers.length) { clearTimeout(state.timers.pop()); } }

  function finish() {
    if (state.finished) { return; }
    state.finished = true;
    clearTimers();
    var rootEl = state.root;
    document.documentElement.classList.remove('mk-lock');
    if (rootEl) {
      rootEl.classList.add('is-done');
      if (rootEl.parentNode && state.removeOnFinish) { rootEl.parentNode.removeChild(rootEl); }
    }
    if (state.site) {
      state.site.classList.add('is-live');
      state.site.classList.remove('is-revealed');
    }
    try { document.dispatchEvent(new CustomEvent('markipie:intro:complete')); } catch (e) { /* old browsers */ }
    if (state.resolve) { state.resolve(); }
    state.playing = false;
  }

  function leave() {
    var rootEl = state.root;
    if (!rootEl || state.finished) { return; }
    rootEl.classList.add('is-leaving');
    if (state.site) { state.site.classList.add('is-revealed'); }
    later(finish, reduceMotion ? T.reduced.exitDuration + 200 : T.exitDuration + 320);
  }

  /* Public: play the intro. Resolves when the website is fully revealed. */
  function play(options) {
    options = options || {};
    if (state.playing) { return state.promise; }
    var siteEl = options.siteSelector ? document.querySelector(options.siteSelector) : (options.site || null);
    var rootEl = options.root ? (typeof options.root === 'string' ? document.querySelector(options.root) : options.root) : null;
    state.removeOnFinish = options.removeOnFinish !== false;

    var storageKey = 'markipie:intro:seen';
    var seen = false;
    if (options.oncePerSession) {
      try { seen = !!root.sessionStorage.getItem(storageKey); root.sessionStorage.setItem(storageKey, '1'); } catch (e) { /* private mode */ }
    }

    state.promise = new Promise(function (resolve) {
      state.resolve = resolve;
      state.finished = false;
      state.playing = true;
      state.site = siteEl;

      if (seen || options.skip) {
        if (rootEl) { rootEl.classList.add('is-done'); if (rootEl.parentNode) { rootEl.parentNode.removeChild(rootEl); } }
        state.root = rootEl;
        finish();
        return;
      }

      if (!rootEl) {
        rootEl = document.createElement('div');
        document.body.insertBefore(rootEl, document.body.firstChild);
      }
      state.root = buildIntro(rootEl);
      document.documentElement.classList.add('mk-lock');

      var exitAt = reduceMotion ? T.reduced.exit : T.exit;
      if (typeof options.holdExtra === 'number') { exitAt += options.holdExtra; }

      /* Start on the next frame so initial styles are committed before the animations begin. */
      var kick = function () {
        rootEl.classList.add('is-playing');
        if (!reduceMotion) {
          later(function () { rootEl.classList.add('is-glowing'); }, T.glow);
          later(function () { rootEl.classList.add('is-shining'); }, T.shine);
        } else {
          later(function () { rootEl.classList.add('is-glowing'); }, T.reduced.fade);
        }
        later(leave, exitAt);
        /* Safety net: whatever happens, never trap the visitor behind the overlay. */
        later(finish, exitAt + 4000);
      };
      if (root.requestAnimationFrame) { root.requestAnimationFrame(function () { root.requestAnimationFrame(kick); }); }
      else { setTimeout(kick, 16); }
    });
    return state.promise;
  }

  /* Public: end the intro immediately (e.g. on a "skip" key). */
  function skip() {
    if (!state.playing || state.finished) { return; }
    clearTimers();
    leave();
  }

  return {
    version: '1.0.0',
    play: play,
    skip: skip,
    renderWordmark: renderWordmark,
    LETTERS: LETTERS,
    VIEWBOX: VIEWBOX,
    COLORS: COLORS,
    TIMELINE: T,
    prefersReducedMotion: reduceMotion
  };
}));
'''
