def keyframes_css():
    lines = ['@keyframes mk-enter {']
    for p, f in samples(2):
        parts = []
        if p == 0:
            parts.append('opacity: 0;')
        elif p == 8 or p == 100:
            parts.append('opacity: 1;')
        if p == 100:
            tr = 'translate3d(0, 0, 0) scale(1)'
        else:
            fs = f'{f:.4f}'
            sc = f'{1 + 0.06 * f:.4f}'
            tr = (f'translate3d(calc(var(--ux) * var(--mk-e) * {fs}), '
                  f'calc(var(--uy) * var(--mk-e) * {fs}), 0) scale({sc})')
        parts.append(f'transform: {tr};')
        lines.append(f'  {p}% {{ {" ".join(parts)} }}')
    lines.append('}')
    return '\n'.join(lines)

