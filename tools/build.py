# ------------------------------------------------------------------ entry directions (unit vectors, screen coords)
D = 0.74  # diagonal component
DIRS = {
    'M':  (-1, 0),      # from the left
    'a':  (D, -D),      # from the upper-right
    'r':  (-D, D),      # from the bottom-left
    'k':  (1, 0),       # from the right
    'i1': (0, -1),      # from the top
    'p':  (D, D),       # from the lower-right
    'i2': (-1, 0),      # from the left
    'e':  (0, 1),       # from the bottom
}
ORDER = ['M', 'a', 'r', 'k', 'i1', 'p', 'i2', 'e']

def r2(v):
    return float(f'{v:.3f}')

letter_data = []
for L in letters:
    bx, by, bw, bh = L['bbox']
    entry = dict(
        id=L['id'], char=L['char'], d=L['d'], fill=L['fill'],
        box=[r2(bx), r2(by), r2(bw), r2(bh)],
    )
    if L['id'] in DIRS:
        entry['dir'] = list(DIRS[L['id']])
        entry['order'] = ORDER.index(L['id'])
    if L['extra'].get('tris'):
        entry['tris'] = L['extra']['tris']
        entry['grad'] = [r2(L['extra']['grad'][0]), r2(L['extra']['grad'][1])]
    letter_data.append(entry)

LETTERS_JSON = json.dumps(letter_data, separators=(',', ':'))

