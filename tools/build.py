def static_svg():
    parts = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{VX} {VY} {VW} {VH}" role="img" aria-label="Markipie">',
             '<title>Markipie</title>',
             f'<defs><linearGradient id="gradM" gradientUnits="userSpaceOnUse" x1="8.95" y1="0" x2="65.55" y2="0">'
             f'<stop offset="0" stop-color="{COLORS["blue"]}"/><stop offset="1" stop-color="{COLORS["teal"]}"/></linearGradient></defs>']
    for L in letters:
        fill = 'url(#gradM)' if L['fill'] == 'gradM' else COLORS[L['fill']]
        parts.append(f'<path id="{L["id"]}" d="{L["d"]}" fill="{fill}"/>')
        for i, t in enumerate(L['extra'].get('tris', [])):
            parts.append(f'<path id="M-piece-{i+1}" d="{t}" fill="{fill}"/>')
    parts.append('</svg>')
    return '\n'.join(parts)
